"""From Imagetext to Worldtext: narration and sound.
   python3 build_sound.py  ->  ../timing.js, ../narration.mp3 (for the page), and $BUILD/narration.m4a (for the mp4)
   Voice: Kokoro (kokoro-onnx), am_michael, one sentence at a time, model files in $KOKORO_DIR (default ~/kokoro).
   Two words are given exact phonemes because the default reading is wrong: Wittgenstein, Cyberiad.
   Sound, synthesized here and kept far under the voice: a soft thread pluck each time Bolas attaches a thread
   (times read from stage.js), and a page tick at each change of scene."""
import hashlib, json, os, subprocess, wave
import numpy as np
from scipy.signal import butter, sosfilt, resample_poly

HERE = os.path.dirname(os.path.abspath(__file__)); WT = os.path.dirname(HERE)
KDIR = os.environ.get('KOKORO_DIR', '/home/claude/kokoro')
BUILD = os.environ.get('BUILD', '/home/claude/worldtext-build')
SR = 48000; VOICE = 'am_michael'; SPEED = 0.98; LANG = 'en-us'
LEAD, GAP = 0.7, 0.42
rng = np.random.default_rng(22)
deck = json.loads(subprocess.check_output(['node', '-e', "console.log(JSON.stringify(require('./deck.js')))"], cwd=WT))
FIX = {'wˈɪtdʒənstˌaɪn': 'vˈɪtɡənʃtˌaɪn', 'sˈaɪbɚɹˌaɪæd': 'saɪbˈɪɹiæd'}

_k = None
def kokoro():
    global _k
    if _k is None:
        from kokoro_onnx import Kokoro
        _k = Kokoro(os.path.join(KDIR, 'kokoro-v1.0.onnx'), os.path.join(KDIR, 'voices-v1.0.bin'))
    return _k
def speak(text):
    os.makedirs(os.path.join(BUILD, 'voice-cache'), exist_ok=True)
    key = hashlib.md5(f'{VOICE}|{SPEED}|{text}|v2'.encode()).hexdigest()[:16]
    p = os.path.join(BUILD, 'voice-cache', key + '.npy')
    if os.path.exists(p): return np.load(p).astype(np.float64)
    ph = kokoro().tokenizer.phonemize(text, LANG)
    for a, b in FIX.items(): ph = ph.replace(a, b)
    a, sr = kokoro().create(ph, voice=VOICE, speed=SPEED, lang=LANG, is_phonemes=True)
    a = resample_poly(a.astype(np.float64), SR, sr)
    nz = np.nonzero(np.abs(a) > 0.01)[0]
    a = a[max(0, nz[0] - int(0.03 * SR)): nz[-1] + int(0.15 * SR)] if len(nz) else a[:1]
    np.save(p, a.astype(np.float32)); return a

# ---------------- timing ----------------
scenes, t = [], 0.0; clips = []
for sc in deck['scenes']:
    c = LEAD; ss = []
    for s in sc['say']:
        a = speak(s['t']); d = len(a) / SR
        ss.append(dict(t0=round(c, 3), t1=round(c + d, 3))); clips.append((t + c, a)); c += d + GAP
    d = round(c - GAP + sc.get('tail', 2.0), 3)
    scenes.append(dict(id=sc['id'], t0=round(t, 3), d=d, s=ss)); t += d
TOTAL = round(t, 3)
TM = dict(voice=VOICE, total=TOTAL, scenes=scenes)
open(os.path.join(WT, 'timing.js'), 'w').write('/* generated by src/build_sound.py from the narration audio: scene starts, lengths, and each sentence\'s start and end (seconds) */\n(function (r) { r.TIMING = ' + json.dumps(TM) + '; })(typeof window !== "undefined" ? window : globalThis);\n')
for s in scenes: print(f"{s['id']:11s} t0={s['t0']:7.2f} d={s['d']:6.2f}")
print('total', TOTAL, f'{int(TOTAL // 60)}:{TOTAL % 60:04.1f}')
if os.environ.get('TIMING_ONLY'): raise SystemExit

EV = json.loads(subprocess.check_output(['node', os.path.join(HERE, 'events.js')]))

# ---------------- sounds ----------------
def filt(x, kind, f, order=2): return sosfilt(butter(order, f, btype=kind, fs=SR, output='sos'), x)
def tt(d): return np.arange(int(d * SR)) / SR
def pluck(f):
    """a thread plucked: a soft fundamental, a faint octave, a breath of attack"""
    t = tt(0.9); e = np.exp(-t / 0.22)
    x = np.sin(2 * np.pi * f * t) * e + 0.25 * np.sin(2 * np.pi * 2.01 * f * t) * np.exp(-t / 0.09) + 0.08 * np.sin(2 * np.pi * 3.02 * f * t) * np.exp(-t / 0.05)
    k = int(0.003 * SR); x[:k] += filt(rng.standard_normal(k), 'highpass', 2000) * 0.3 * np.linspace(1, 0, k)
    x[:int(0.002 * SR)] *= np.linspace(0, 1, int(0.002 * SR)); return filt(x, 'lowpass', 5000)
def tick():
    """a page tick: a dry paper touch and a small knock"""
    t = tt(0.08); n = filt(filt(rng.standard_normal(len(t)), 'highpass', 1500), 'lowpass', 7000) * np.exp(-t / 0.012)
    th = np.sin(2 * np.pi * 180 * t) * np.exp(-t / 0.02) * 0.4
    return n * 0.8 + th
N = int((TOTAL + 1.0) * SR)
V = np.zeros(N); FX = np.zeros((2, N))
for st, a in clips: i = int(st * SR); V[i:i + len(a)] += a[:N - i]
def put(t0, sig, g, pan):
    i = int(t0 * SR); n = min(len(sig), N - i)
    if n <= 0: return
    FX[0, i:i + n] += sig[:n] * g * np.sqrt((1 - pan) / 2) * 1.414; FX[1, i:i + n] += sig[:n] * g * np.sqrt((1 + pan) / 2) * 1.414
NOTES = [523.25, 587.33, 659.25, 783.99, 880.0]
for si, (s, evs) in enumerate(zip(scenes, EV)):
    if si: put(s['t0'] + 0.02, tick(), 1.0, -0.2)
    last = -9
    for j, e in enumerate(evs):
        if e - last < 0.12: continue
        put(s['t0'] + e, pluck(NOTES[(si + j) % len(NOTES)]), 0.55, 0.25 * np.sin(j * 1.7)); last = e
# levels: voice peak at -1 dBFS; the sound layer's peak held 24 dB or more below the voice's level after normalization
V *= 10 ** (-1 / 20) / np.abs(V).max()
def limit(x, thr_db=-9.0):
    """a gentle look-ahead peak limiter on the voice, so that loudness normalization can stay a plain gain"""
    thr = 10 ** (thr_db / 20); w = int(0.004 * SR)
    env = np.maximum.accumulate(np.abs(x))  # placeholder, replaced below
    a = np.abs(x); pad = np.concatenate([a, np.zeros(w)])
    from numpy.lib.stride_tricks import sliding_window_view
    env = sliding_window_view(pad, w + 1).max(1)[:len(x)]
    g = np.minimum(1.0, thr / np.maximum(env, 1e-9))
    rel = np.exp(-1 / (0.08 * SR)); out = np.empty_like(g); cur = 1.0
    for i in range(len(g)):
        cur = g[i] if g[i] < cur else g[i] + (cur - g[i]) * rel
        out[i] = cur
    return x * out
V = limit(V) * 10 ** (8 / 20)
V *= 10 ** (-1 / 20) / np.abs(V).max()
FX *= 10 ** (-30 / 20) / max(1e-9, np.abs(FX).max())
mix = np.stack([V + FX[0], V + FX[1]], 1)
wp = os.path.join(BUILD, 'mix.wav')
with wave.open(wp, 'wb') as wf:
    wf.setnchannels(2); wf.setsampwidth(2); wf.setframerate(SR); wf.writeframes((np.clip(mix, -1, 1) * 32767).astype('<i2').tobytes())
# two-pass loudnorm to -16 LUFS
o = subprocess.run(['ffmpeg', '-hide_banner', '-i', wp, '-af', 'loudnorm=I=-16:TP=-1.5:LRA=11:print_format=json', '-f', 'null', '-'], capture_output=True, text=True).stderr
m = json.loads(o[o.rindex('{'):o.rindex('}') + 1])
af = f"loudnorm=I=-16:TP=-1.5:LRA=11:measured_I={m['input_i']}:measured_TP={m['input_tp']}:measured_LRA={m['input_lra']}:measured_thresh={m['input_thresh']}:offset={m['target_offset']}:linear=true"
subprocess.check_call(['ffmpeg', '-y', '-loglevel', 'error', '-i', wp, '-af', af, '-ar', '48000', '-c:a', 'aac', '-b:a', '160k', os.path.join(BUILD, 'narration.m4a')])
subprocess.check_call(['ffmpeg', '-y', '-loglevel', 'error', '-i', wp, '-af', af, '-ar', '44100', '-ac', '1', '-c:a', 'libmp3lame', '-b:a', '64k', os.path.join(WT, 'narration.mp3')])
gain_db = -16 - float(m['input_i'])
print('normalization', m.get('normalization_type'), 'loudnorm gain dB', round(gain_db, 2), '| sound layer peak after gain dBFS', round(-30 + gain_db, 1), '| voice peak after gain dBFS', round(-1 + gain_db, 1))
print('events', sum(len(e) for e in EV), 'done', TOTAL)
